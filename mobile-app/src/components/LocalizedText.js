export function useLocalizeText() {
  const { language } = useLocale();
  return React.useCallback((value, values) => localizeText(value, language, values), [language]);
}

export default function LocalizedText({ children, values, translate = true, ...props }) {
  const { language } = useLocale();
  return <NativeText {...props}>{React.Children.map(children, (child) => translate === false ? child : localizeText(child, language, values))}</NativeText>;
}
