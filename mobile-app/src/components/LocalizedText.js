export function localizeText(value, language, values) {
  if (typeof value !== "string") return value;
  const padding = value.match(/^\s*/)?.[0] || "";
  const tail = value.match(/\s*$/)?.[0] || "";
  const core = value.trim();
  const hit = language === "en" ? core : phrases[language]?.[core];
  if (language !== "en" && core && !hit && typeof __DEV__ !== "undefined" && __DEV__) {
    // eslint-disable-next-line no-console
    console.warn(`[i18n] missing ${language} phrase: "${core}"`);
  }
  const translated = hit ? `${padding}${hit}${tail}` : value;
  return values ? translated.replace(/\{(\w+)\}/g, (token, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : token
  ) : translated;
}

